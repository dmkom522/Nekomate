function restoreChineseError(text, depth = 0) {
  if (typeof text !== 'string') return text;
  if (chineseErrors.has(text)) return chineseErrors.get(text);
  if (depth >= 8) return text;
  for (const [pattern, format] of reverseErrors) {
    const match = pattern.exec(text);
    if (match) return format(match, value => restoreChineseError(value, depth + 1));
  }
  return text;
}
export function translateMessage(text, language = 'zh-CN') {
  if (normalizeLanguage(language) === 'zh-CN') return restoreChineseError(text);
  const result = translate(text, language);
  if (language === 'en' && typeof result === 'string' && /\p{Script=Han}/u.test(result)) return 'The operation could not be completed. Check your settings and try again.';
  return result;
}
