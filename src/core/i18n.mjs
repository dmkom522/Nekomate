export function translate(text, language = 'zh-CN') {
  if (typeof text !== 'string') return text;
  if (normalizeLanguage(language) !== 'en') return text;
  if (Object.hasOwn(ENGLISH, text)) return ENGLISH[text];
  for (const [pattern, format] of dynamic) { const match = pattern.exec(text); if (match) return format(...match.slice(1)); }
  return text;
}

// IPC errors may already be localized when they are saved in chat history. Only
// recognize our own catalog and error envelopes; never translate arbitrary prose.
const chineseErrors = new Map();
for (const [chinese, english] of Object.entries(ENGLISH)) {
  if (!chineseErrors.has(english)) chineseErrors.set(english, chinese);
}
